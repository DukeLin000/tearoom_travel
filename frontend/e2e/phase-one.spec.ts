import { expect, test } from '@playwright/test';

test('sign in, create trip, edit activity and reconcile budget after deletion', async ({ page }) => {
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  await page.goto('/');
  await page.getByLabel('測試使用者代號').fill(`e2e-${suffix}`);
  await page.getByLabel('顯示名稱').fill('測試旅人');
  await page.getByRole('button', { name: '開始規劃 →' }).click();
  await page.getByRole('button', { name: '建立第一趟旅程' }).click();
  await page.getByLabel('旅程名稱').fill(`沖繩 ${suffix}`);
  await page.getByLabel('目的地').fill('沖繩');
  await page.getByLabel('開始日期').fill('2027-03-12');
  await page.getByLabel('結束日期').fill('2027-03-14');
  await page.getByLabel('時區').fill('Asia/Tokyo');
  await page.getByLabel('預算上限').fill('100.00');
  await page.getByRole('button', { name: '建立旅程', exact: true }).click();
  await expect(page.getByRole('heading', { name: `沖繩 ${suffix}` })).toBeVisible();
  await expect(page.getByRole('button', { name: /DAY/ })).toHaveCount(3);
  await page.getByRole('button', { name: '＋ 新增行程' }).click();
  await page.getByLabel('活動名稱').fill('海邊午餐');
  await page.getByLabel('活動預估金額（整體旅程）').fill('0.10');
  await page.getByRole('button', { name: '儲存行程' }).click();
  await expect(page.getByRole('heading', { name: '海邊午餐' })).toBeVisible();
  await page.getByRole('button', { name: '旅程預算', exact: true }).click();
  await expect(page.getByText('TWD 99.90', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '每日行程' }).click();
  await page.getByRole('button', { name: '編輯 海邊午餐' }).click();
  await page.getByLabel('活動預估金額（整體旅程）').fill('25.50');
  await page.getByRole('button', { name: '儲存行程' }).click();
  await expect(page.getByText('TWD 25.50', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '旅程預算', exact: true }).click();
  await expect(page.getByText('TWD 74.50', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '每日行程' }).click();
  await page.getByRole('button', { name: '編輯 海邊午餐' }).click();
  await page.getByRole('button', { name: '刪除行程', exact: true }).click();
  await page.getByRole('button', { name: '確認刪除' }).click();
  await expect(page.getByRole('heading', { name: '海邊午餐' })).toHaveCount(0);
  await page.getByRole('button', { name: '旅程預算', exact: true }).click();
  await expect(page.getByText('TWD 100.00', { exact: true })).toHaveCount(2);
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => document.documentElement.clientWidth));
  await page.getByRole('button', { name: '登出' }).click();
  await expect(page.getByRole('button', { name: '開始規劃 →' })).toBeVisible();
});
